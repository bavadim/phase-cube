(() => {
  'use strict';
  // The handbook, pre-action hints and post-action feedback use the same
  // vocabulary as the controls. Read outcomes from the score's actual gates.
  const gears = ['Бочка', 'Мелодия'];
  const noteNames = ['До','До♯','Ре','Ми♭','Ми','Фа','Фа♯','Соль','Соль♯','Ля','Си♭','Си'];
  const pitchName = midi => noteNames[midi % 12] + (Math.floor(midi / 12) - 1);
  function passed(state, predicate) {
    return Array.from({length:FactoryScore.STEPS}, (_, i) => FactoryScore.eventAt(state, i))
      .filter(predicate).map(hit => hit.step + 1);
  }
  const steps = numbers => numbers.length ? numbers.join(', ') : '—';
  const metal = state => passed(state, hit => hit.route === 'metal');
  const stamps = state => passed(state, hit => hit.stamp);
  function imprint(state) {
    const hits = stamps(state);
    return hits.length ? 'Штамп бьёт на шагах ' + steps(hits) + '.' : 'В этом такте штамп молчит.';
  }
  const parts = {
    gears: {
      name:'Шестерни бочки и мелодии',
      ports:'Вал мотора вращает оба колеса. Один оборот каждого проигрывает один такт его партии. Метки на ободе — моменты звучания.',
      gesture:'Коснитесь обода для задержки на ⅛ такта. Проведите по ободу вправо или влево для сдвига в обе стороны. Тяните ступицу вверх или вниз либо нажимайте + и − на самой детали для изменения громкости.',
      cycle:'Восемь положений фазы по кругу (C₈). У ровной бочки рисунок на слух повторяется через два щелчка. Громкость идёт от 0 до 2× с шагом 0,25×. При нуле колесо продолжает передавать движение.',
      now:state => state.gears.map((gear,i) => gears[i] + ' · сдвиг ' + gear.phase + '/8, ' + gear.level.toLocaleString('ru') + '×').join('  /  ')
    },
    belt: {
      name:'Конвейер и коробки',
      ports:'Один оборот ленты подаёт восемь коробок в стрелку. Каждая коробка несёт свою ноту.',
      gesture:'Коснитесь коробки для следующей ноты из басовой партии. На клавиатуре ← и → перебирают ноты выбранной коробки в обе стороны. На паузе ноту можно услышать отдельно.',
      cycle:'После последней высоты снова звучит первая. Позиция, длительность и сила удара у каждой коробки заданы рисунком ленты.',
      now:state => state.notes.map(pitchName).join(' · ')
    },
    drum: {
      name:'Барабан и стрелка',
      ports:'На входе коробка. Язычок под стрелкой направляет её в один из двух приёмников. Высота ноты сохраняется, меняется тембр.',
      gesture:'Касание цветного язычка меняет стекло на металл и обратно. Касание центра сдвигает весь рисунок маршрутов на один шаг. Проведите по центру влево, чтобы сдвинуть его обратно.',
      cycle:'Два положения у каждого язычка (C₂). Восемь щелчков возвращают барабан в исходную ориентацию (C₈).',
      now:state => 'Металл на шагах ' + steps(metal(state)) + '. Стекло на шагах ' + steps(passed(state, hit => hit.route === 'glass')) + '.'
    },
    clutch: {
      name:'Муфта совпадений',
      ports:'На входе — удар по металлу. При включённой муфте тяга доходит до штампа, только если на этом шаге щупы обоих дисков попали в прорези. Сам металл звучит при каждом попадании.',
      gesture:'Касание диска I или II сдвигает его прорези на шаг. Свайп влево возвращает диск на шаг. Рычаг «Муфта» включает прямой привод или снова вводит диски в работу.',
      cycle:'По восемь углов на каждом диске и два положения рычага (C₈ × C₈ × C₂). На диске I прорези идут через одну, поэтому через два щелчка он снова пропускает те же шаги.',
      now:state => (state.clutch ? 'Совпадения прорезей на шагах ' + steps(passed(state, e => e.open.every(Boolean))) + '. ' : 'Прямой привод. ') +
        'Металл на шагах ' + steps(metal(state)) + '. ' + imprint(state)
    },
    ends: {
      name:'Мотор A, приёмники и штамп B',
      ports:'Мотор задаёт общий ход. Стекло и металл озвучивают пришедшую коробку. Удар штампа добавляет рабочий барабан и оставляет оттиск на бумаге.',
      gesture:'«Запустить» и «Пауза» управляют мотором. Приёмники и пресс срабатывают автоматически. Чтобы изменить их партии, настройте стрелку и муфту.',
      cycle:'Восемь шагов на такт. Бумага показывает последние восемь шагов, прошедших при воспроизведении.',
      now:imprint
    }
  };
  const operations = {
    gearPhase: ['gears','Обод · коснитесь для сдвига на ⅛, проведите влево для обратного сдвига.'],
    gearLevel: ['gears','Ступица · потяните вверх или вниз для изменения громкости. Один шаг кнопкой + или −.'],
    note: ['belt','Коробка · коснитесь для следующей ноты. На паузе она сразу прозвучит.'],
    tab: ['drum','Язычок · коснитесь, чтобы направить ноту в другой приёмник.'],
    rotor: ['drum','Центр барабана · коснитесь, чтобы сдвинуть сразу все восемь маршрутов. Свайп влево возвращает на шаг.'],
    disc: ['clutch','Диск муфты · коснитесь для сдвига прорезей на шаг. Проведите влево для обратного сдвига.'],
    clutch: ['clutch','Рычаг · переключите фильтр совпадений и прямой привод от металла к штампу.']
  };
  function feedback(type, i, state) {
    switch (type) {
      case 'gearPhase': return gears[i] + ' · сдвиг на ' + state.gears[i].phase + '/8 такта.';
      case 'gearLevel': return gears[i] + ' · громкость ' + state.gears[i].level.toLocaleString('ru') + '×.';
      case 'note': return 'Коробка ' + (i+1) + ' · ' + pitchName(state.notes[i]) + '.';
      case 'tab': return 'Язычок ' + (i+1) + ' → ' + (state.routes[i] ? 'металл. ' : 'стекло. ') + imprint(state);
      case 'rotor': return 'Сдвиг барабана ' + state.rotor + '/8. ' + imprint(state);
      case 'disc': return 'Диск ' + (i ? 'II' : 'I') + ' · сдвиг ' + state.discs[i] + '/8. ' + (state.clutch ? imprint(state) : 'Сейчас включён прямой привод.');
      case 'clutch': return (state.clutch ? 'Оба диска включены. ' : 'Включён прямой привод. ') + imprint(state);
    }
  }
  window.LineParts = {parts, operations, feedback};
})();
